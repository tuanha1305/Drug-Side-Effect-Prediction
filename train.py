def set_seed(seed: int):
    """Set random seed for reproducibility"""
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    np.random.seed(seed)
    import random
    random.seed(seed)

    if torch.cuda.is_available():
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


def load_data(config: Config):
    """
    Load and prepare data.
    MUST load ALL data (including additional negatives) to align with
    indices stored in cv_splits.pkl generated by preprocessing.py.
    """
    logger.info("=" * 60)
    logger.info("Loading Data")
    logger.info("=" * 60)

    # Load drug SMILES
    drug_smiles_path = config.data.raw_data_dir / config.data.drug_smiles_file
    if not drug_smiles_path.exists():
        raise FileNotFoundError(f"Drug SMILES file not found: {drug_smiles_path}")

    drug_dict, drug_smiles = load_drug_smiles(str(drug_smiles_path))

    # Create SMILES encoder
    vocab_path = config.data.raw_data_dir / config.data.vocab_file
    subword_map_path = config.data.raw_data_dir / config.data.subword_map_file

    logger.info("Creating SMILES encoder...")
    smiles_encoder = create_smiles_encoder(
        vocab_path=str(vocab_path),
        subword_map_path=str(subword_map_path),
        max_len=config.data.max_drug_len,
        use_cache=True
    )

    # Load drug-side effect matrix
    drug_side_pkl = config.data.raw_data_dir / config.data.drug_side_pkl
    if not drug_side_pkl.exists():
        raise FileNotFoundError(f"Drug-side matrix not found: {drug_side_pkl}")

    drug_side_matrix = load_drug_side_matrix(str(drug_side_pkl))

    # Extract samples
    logger.info("Extracting samples...")

    addition_neg, final_pos, final_neg = extract_positive_negative_samples(
        drug_side_matrix,
        addition_negative_strategy='all'
    )

    # --- FIXED HERE: Combine ALL samples to match indices in cv_splits.pkl ---
    all_negatives = np.vstack((final_neg, addition_neg))
    final_sample = np.vstack((final_pos, all_negatives))

    # Create DataFrame
    logger.info("Creating DataFrame...")
    df = prepare_dataframes(final_sample, drug_smiles)

    logger.info(f"Total samples loaded: {len(df)}")
    return df, drug_smiles, smiles_encoder


def load_cv_splits(config: Config, df):
    """Load or create 5-fold cross-validation splits"""
    splits_path = config.data.processed_data_dir / "cv_splits.pkl"
    config.data.processed_data_dir.mkdir(parents=True, exist_ok=True)

    if splits_path.exists():
        logger.info(f"Loading CV splits from: {splits_path}")
        with open(splits_path, 'rb') as f:
            splits = pickle.load(f)

        # Verify n_splits matches config
        if len(splits) != config.data.n_folds:
            logger.warning(f"Saved splits have {len(splits)} folds, but config requests {config.data.n_folds}.")
            logger.warning("Recreating splits...")
            splits = _create_new_splits(config, df, splits_path)
    else:
        splits = _create_new_splits(config, df, splits_path)

    return splits

def _create_new_splits(config, df, path):
    logger.info(f"Creating new {config.data.n_folds}-fold CV splits...")
    from sklearn.model_selection import StratifiedKFold

    X = np.zeros(len(df)) # Placeholder
    # Stratify by Label (Frequency 0-5)
    y = df['Label'].values

    skf = StratifiedKFold(
        n_splits=config.data.n_folds,
        random_state=config.data.random_state,
        shuffle=True
    )

    splits = list(skf.split(X, y))

    with open(path, 'wb') as f:
        pickle.dump(splits, f)
    logger.info(f"Saved CV splits to: {path}")
    return splits


def load_side_effect_data(config: Config, fold: int):
    """Load pre-computed side effect substructures"""
    se_index_path = config.data.processed_data_dir / f"SE_sub_index_{config.data.top_k_substructures}_{fold}.npy"
    se_mask_path = config.data.processed_data_dir / f"SE_sub_mask_{config.data.top_k_substructures}_{fold}.npy"

    if not se_index_path.exists() or not se_mask_path.exists():
        raise FileNotFoundError(
            f"Side effect data not found for fold {fold}. "
            "Please run 'preprocess_data.py' first."
        )

    se_index = np.load(se_index_path)
    se_mask = np.load(se_mask_path)
    return se_index, se_mask


def train_fold(
        config: Config,
        fold: int,
        train_df: pd.DataFrame,
        val_df: pd.DataFrame,
        train_indices: np.ndarray,
        val_indices: np.ndarray,
        train_labels: np.ndarray,
        val_labels: np.ndarray,
        se_index: np.ndarray,
        se_mask: np.ndarray,
        smiles_encoder
):
    """Train model for one fold"""
    logger.info("=" * 60)
    logger.info(f"Training Fold {fold}")
    logger.info("=" * 60)

    # Create dataloaders
    # dataset.py handles balancing (Negative Sampling) internally here
    # It will downsample the large amount of negatives in train_indices
    train_loader, val_loader = create_dataloaders(
        config=config,
        train_df=train_df,
        val_df=val_df,
        train_indices=train_indices,
        val_indices=val_indices,
        train_labels=train_labels,
        val_labels=val_labels,
        se_index=se_index,
        se_mask=se_mask,
        smiles_encoder=smiles_encoder,
        fold=fold
    )

    # Create model
    logger.info("Creating model (HSTrans)...")
    model = create_model(config.model, device=config.device)

    # Create trainer
    trainer = Trainer(
        model=model,
        config=config,
        train_loader=train_loader,
        val_loader=val_loader,
        fold=fold
    )

    # Train
    trainer.train()

    # Evaluate using the corrected Evaluator
    logger.info("Evaluating on validation set...")
    evaluator = Evaluator(model, device=config.device)
    metrics = evaluator.evaluate(val_loader)
    evaluator.print_metrics(metrics)

    # Save metrics
    results_path = config.paths.result_dir / f"fold_{fold}_results.json"
    with open(results_path, 'w') as f:
        json.dump(metrics, f, indent=4)

    return trainer, metrics


def train_all_folds(config: Config, args):
    """Train all folds (5-Fold CV)"""
    logger.info("=" * 60)
    logger.info("Starting 5-Fold Cross-Validation")
    logger.info("=" * 60)

    # Load data
    df, drug_smiles, smiles_encoder = load_data(config)

    # Load CV splits
    splits = load_cv_splits(config, df)

    all_metrics = []

    start = args.start_fold
    end = min(args.end_fold, len(splits))

    for fold_idx in range(start, end):
        train_indices, val_indices = splits[fold_idx]

        # Prepare fold data
        # df has ~745k rows. Indices go up to ~745k.
        # iloc works correctly now.
        train_df = df.iloc[train_indices].reset_index(drop=True)
        val_df = df.iloc[val_indices].reset_index(drop=True)

        train_labels = df.iloc[train_indices]['Label'].values
        val_labels = df.iloc[val_indices]['Label'].values

        # Load fold-specific side effect data
        se_index, se_mask = load_side_effect_data(config, fold_idx)

        # Train
        trainer, metrics = train_fold(
            config=config,
            fold=fold_idx,
            train_df=train_df,
            val_df=val_df,
            train_indices=np.arange(len(train_df)),
            val_indices=np.arange(len(val_df)),
            train_labels=train_labels,
            val_labels=val_labels,
            se_index=se_index,
            se_mask=se_mask,
            smiles_encoder=smiles_encoder
        )

        all_metrics.append(metrics)

    logger.info("=" * 60)
    logger.info("Aggregated Cross-Validation Results")
    logger.info("=" * 60)

    if all_metrics:
        agg_results_display = Evaluator.aggregate_fold_results(all_metrics, display_format='paper')
        Evaluator.print_fold_results(agg_results_display)

        agg_results_raw = Evaluator.aggregate_fold_results(all_metrics, display_format='dict')
        agg_path = config.paths.result_dir / "aggregated_results.json"
        with open(agg_path, 'w') as f:
            json.dump(agg_results_raw, f, indent=4)
        logger.info(f"Saved aggregated results to: {agg_path}")


def main():
    parser = argparse.ArgumentParser(description='Train HSTrans Model')

    parser.add_argument('--config', type=str, default='default',
                        choices=['default', 'fast', 'memory_efficient'])
    parser.add_argument('--epochs', type=int, default=None)
    parser.add_argument('--batch_size', type=int, default=None)
    parser.add_argument('--lr', type=float, default=None)
    parser.add_argument('--device', type=str, default=None)

    parser.add_argument('--start_fold', type=int, default=0)
    parser.add_argument('--end_fold', type=int, default=5,
                        help='End fold index (default 5 for 5-fold CV)')

    parser.add_argument('--use_cross_attention', action='store_true',
                        help='Enable cross-attention (Experimental: Not in HSTrans paper)')

    parser.add_argument('--data_dir', type=str, default='data/raw')
    parser.add_argument('--output_dir', type=str, default='outputs')

    parser.add_argument('--seed', type=int, default=42)

    args = parser.parse_args()
    set_seed(args.seed)

    if args.config == 'default':
        config = get_default_config()
    elif args.config == 'fast':
        config = get_fast_config()
    elif args.config == 'memory_efficient':
        config = get_memory_efficient_config()

    if args.lr: config.training.learning_rate = args.lr
    if args.batch_size: config.training.batch_size = args.batch_size
    if args.epochs: config.training.num_epochs = args.epochs
    if args.device: config.device = args.device

    config.data.n_folds = 5
    config.model.use_cross_attention = args.use_cross_attention

    config.data.raw_data_dir = Path(args.data_dir)
    config.paths.result_dir = Path(args.output_dir) / "results"
    config.paths.checkpoint_dir = Path(args.output_dir) / "checkpoints"
    config.paths.log_dir = Path(args.output_dir) / "logs"

    for p in [config.paths.result_dir, config.paths.checkpoint_dir, config.paths.log_dir]:
        p.mkdir(parents=True, exist_ok=True)

    config.save(str(config.paths.result_dir / "config.json"))

    train_all_folds(config, args)


if __name__ == "__main__":
    main()